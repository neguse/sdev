// Command genlicenses writes the notices of everything compiled into sdev.
package main

import (
	"bytes"
	"fmt"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"runtime"
	"slices"
	"strings"
)

var licenseFile = regexp.MustCompile(`(?i)^(licen[cs]e|copying)(\.(md|txt))?$`)

func main() {
	out, err := exec.Command("go", "list", "-deps", "-f", "{{with .Module}}{{if not .Main}}{{.Path}} {{.Dir}}{{end}}{{end}}", ".").Output()
	if err != nil {
		log.Fatal(err)
	}
	lines := strings.Split(strings.TrimSpace(string(out)), "\n")
	slices.Sort(lines)
	lines = slices.Compact(lines)

	var notices bytes.Buffer
	notices.WriteString("Licenses of the code compiled into sdev. Generated by go generate.\n")
	add := func(name, dir string) {
		entries, err := os.ReadDir(dir)
		if err != nil {
			log.Fatal(err)
		}
		found := false
		for _, e := range entries {
			if !licenseFile.MatchString(e.Name()) {
				continue
			}
			text, err := os.ReadFile(filepath.Join(dir, e.Name()))
			if err != nil {
				log.Fatal(err)
			}
			fmt.Fprintf(&notices, "\n== %s ==\n\n%s\n", name, bytes.TrimSpace(text))
			found = true
		}
		if !found {
			log.Fatalf("%s has no license file in %s", name, dir)
		}
	}
	add("Go standard library", runtime.GOROOT())
	add("devkit-utils", "devkit-utils")
	for _, line := range lines {
		module, dir, _ := strings.Cut(line, " ")
		add(module, dir)
	}
	if err := os.WriteFile("third_party_licenses.txt", notices.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}
